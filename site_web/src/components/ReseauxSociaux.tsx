export const ReseauxSociaux: React.FC<{
  ton?: 'clair' | 'sombre';
  className?: string;
}> = ({ ton = 'clair', className = '' }) => {
  const sociaux = useContenu('sociaux').filter((s) => s.url.trim() !== '' && GLYPHES[s.cle]);
  if (sociaux.length === 0) return null;

  const styles =
    ton === 'sombre'
      ? 'border-white/20 text-on-night-soft hover:border-rve-lime hover:bg-rve-lime hover:text-forest'
      : 'border-line text-ink-soft hover:border-rve-green hover:bg-rve-green hover:text-white';

  return (
    <ul className={`flex flex-wrap items-center gap-2 ${className}`}>
      {sociaux.map((s) => (
        <li key={s.cle}>
          <a
            href={s.url}
            target="_blank"
            rel="noopener noreferrer"
            aria-label={`${s.label} du Réseau Voix EssentiELLES Bénin`}
            title={s.label}
            className={`flex h-10 w-10 items-center justify-center rounded-bouton border transition-colors duration-150 ${styles}`}
          >
            <svg viewBox="0 0 24 24" aria-hidden="true" className="h-[1.125rem] w-[1.125rem]" fill="currentColor">
              <path d={GLYPHES[s.cle]} />
            </svg>
          </a>
        </li>
      ))}
    </ul>
  );
};
